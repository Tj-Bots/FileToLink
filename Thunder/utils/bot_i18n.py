def detect(language_code: Optional[str]) -> str:
    code = (language_code or "").lower().replace("_", "-").split("-")[0]
    if code == "iw":
        code = "he"
    return code if code in T else "en"


def resolve_lang(setting: Optional[str], language_code: Optional[str]) -> str:
    """The user's language: an explicit choice wins, else their Telegram language."""
    return setting if setting in T else detect(language_code)


def tr(lang: str, key: str, **kw: Any) -> str:
    text = T.get(lang, {}).get(key) or T["en"][key]
    return text.format(**kw) if kw else text
